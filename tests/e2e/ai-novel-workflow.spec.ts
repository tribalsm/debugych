import {navigate,preparePlan,openDiff,openAnalytics} from './redesign-helpers';
import {test,expect} from '../../apps/web/node_modules/@playwright/test';
import path from 'node:path';

test('Новый React/TS проект → согласие → AI Engine → Bug Proof → исправление и регрессия',async({page})=>{
 test.setTimeout(180000);
 test.skip(process.env.COMPOSE_CONTRACT_TEST!=='1','Explicit contract provider; not live AI evaluation');
 await page.goto('/');await page.getByRole('button',{name:'Новый проект'}).click();
 await page.getByLabel('Название проекта').fill('Independent React · full workflow');
 await page.getByRole('button',{name:'Создать проект'}).click();
 const root=path.resolve(process.cwd(),'../../evaluation/projects/react_booking');
 await page.getByLabel('Загрузить файлы').setInputFiles(['SeatDesk.tsx','index.html','requirements.md'].map(f=>path.join(root,f)));
 await expect(page.getByText('requirements.md',{exact:true})).toBeVisible();
 const declined=new Promise<void>(resolve=>page.once('dialog',async dialog=>{await dialog.dismiss();resolve()}));
 await preparePlan(page);
 await declined;
 await expect(page.getByRole('heading',{name:'Проверки готовы к запуску'})).toHaveCount(0);
 page.once('dialog',dialog=>dialog.accept());
 await preparePlan(page);
 await navigate(page,'Тесты');
 await expect(page.getByRole('heading',{name:'Seat Desk: бронирование',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Запустить тесты'}).click();
 await expect(page.getByText('2 passed · 2 failed',{exact:false})).toBeVisible({timeout:45000});
 await navigate(page,'Ошибки');
 await page.getByRole('button').filter({hasText:'Весь остаток'}).click();
 await page.getByLabel('Обоснование ожидания').fill('R1 разрешает бронировать весь остаток: исходные 6 мест минус запрошенные 6 должны дать 0.');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Подтвердить ожидание и воспроизвести'}).click();
 await expect(page.getByText('Подтверждено тестом',{exact:true}).first()).toBeVisible({timeout:45000});
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Предложить исправление'}).click();
 await openDiff(page); await expect(page.getByText('+  if(Number.isInteger(amount)&&amount>0&&amount<=available){',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Проверить исправление'}).click();
 await expect(page.getByRole('button',{name:'Подтвердить применение'})).toBeEnabled({timeout:90000});
 page.once('dialog',dialog=>dialog.dismiss());
 await page.getByRole('button',{name:'Подтвердить применение'}).click();
 await expect(page.getByRole('button',{name:'Подтвердить применение'})).toBeEnabled();
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Подтвердить применение'}).click();
 await expect(page.getByRole('button',{name:'Патч применён'})).toBeDisabled();
 await navigate(page,'Отчёт');
 await openAnalytics(page); await expect(page.getByRole('heading',{name:'AI Engine · журнал генераций'})).toBeVisible();
 await expect(page.getByText('Попыток: 3 · валидных ответов: 3 · ошибок: 0',{exact:true})).toBeVisible();
});
