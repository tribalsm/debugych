"""Private operator-only fixture for free infrastructure acceptance.

Never exposed as an API. Explicitly seeds a known offline plan/patch, not LLM
results. All execution, proof and regression must still pass real server gates.
"""
import argparse
import json
from sqlalchemy import select
from apps.api.db import Session, Project, Record, add_record
from apps.api.jobs import DATA
from apps.api.bug_workflow import prepare_patch

SOURCE = 'def add(a, b):\n    return a - b\n'
FIXED = 'def add(a, b):\n    return a + b\n'
TEST = 'from calc import add\n\ndef test_addition():\n    assert add(2, 3) == 5\n\ndef test_zero():\n    assert add(0, 0) == 0\n'

def seed(project_id, bug_id=None):
    with Session() as db:
        project = db.get(Project, project_id)
        assert project and project.name == 'Server 1.0 offline control' and not project.demo
        files = db.scalars(select(Record).where(Record.project_id == project_id, Record.kind == 'file')).all()
        calc = next(f for f in files if f.data['name'] == 'calc.py')
        assert (DATA / calc.data['storage']).read_text() == SOURCE
        if not bug_id:
            assert not db.scalar(select(Record).where(Record.project_id == project_id, Record.kind == 'test'))
            requirement = add_record(db, project_id, 'requirement', {'key':'R1','text':'add(a,b) returns the arithmetic sum of its two inputs.','origin':'offline-control-fixture'})
            test = add_record(db, project_id, 'test', {'title':'Addition and zero','requirement_id':requirement.id,'framework':'pytest','code':TEST,
                'gherkin':'Feature: Addition\nScenario: Sum\n Given inputs 2 and 3\n When add is called\n Then the result is 5\n','origin':'offline-control-fixture','result':'not_run'})
            db.commit()
            return {'project_id':project_id,'test_id':test.id,'origin':'offline-control-fixture','newLLMCalls':0}
        bug = db.get(Record, bug_id)
        assert bug and bug.project_id == project_id and bug.data['status'] == 'confirmed' and bug.data.get('proof_id')
        original = db.get(Record, bug.data['run_id'])
        before = next(f['content'] for f in original.data['snapshot']['files'] if f['path'] == 'calc.py')
        assert before == SOURCE
        import hashlib
        plan = {'explanation':'Known offline acceptance fixture patch. Not generated by LLM in this run.',
                'changes':[{'path':'calc.py','before_sha256':hashlib.sha256(SOURCE.encode()).hexdigest(),'content':FIXED}]}
        proposal = prepare_patch(original.data['snapshot'], plan)
        fix = add_record(db, project_id, 'fix', {**proposal,'bug_id':bug.id,'proof_id':bug.data['proof_id'],'run_id':original.id,
            'project_state_sha256':original.data['project_state_sha256'],'origin':'offline-control-fixture','verified':False,'applied':False,'verification_ids':[]})
        bug.data = {**bug.data,'current_fix_id':fix.id}
        db.commit()
        return {'fix_id':fix.id,'origin':'offline-control-fixture','newLLMCalls':0}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('project_id')
    parser.add_argument('--bug-id')
    args = parser.parse_args()
    print(json.dumps(seed(args.project_id,args.bug_id)))
